const platform = (
  id: string,
  x: number,
  y: number,
  width: number,
  style: PlatformDefinition['style'],
  height = 24,
): PlatformDefinition => ({ id, x, y, width, height, style });
const anchor = (
  id: string,
  x: number,
  y: number,
  left: number,
  right: number,
): CheckpointDefinition => ({
  id,
  spawn: { x, y },
  area: { x: left, y: y - 8, width: right - left, height: 16 },
});
const bird = (
  id: string,
  left: number,
  right: number,
  baseY: number,
  offset: number,
): BirdDefinition => ({
  id,
  left,
  right,
  baseY,
  offset,
  speed: 56,
  direction: 1,
  amplitude: 9,
  frequency: 0.3,
  phase: 0,
});
const rat = (
  id: string,
  left: number,
  right: number,
  speed: number,
): RatDefinition => ({
  id,
  left,
  right,
  floorY: 1450,
  speed,
  offset: (right - left) * 0.7,
  direction: -1,
});
const steam = (
  id: string,
  x: number,
  width: number,
  clearMs: number,
): SteamDefinition => ({
  id,
  x,
  width,
  floorY: 1450,
  height: 160,
  clearMs,
  warningMs: 700,
  hissMs: 200,
  activeMs: 1100,
  dissipateMs: 550,
});

